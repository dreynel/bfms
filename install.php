<?php
// install.php - Universal Web Setup Wizard for Hostinger, Local php -S, & XAMPP
require_once __DIR__ . '/config/app.php';

$message = null;
$error = null;
$connected = false;

// Default detected values
$defaultHost = defined('DB_HOST') ? DB_HOST : 'localhost';
$defaultPort = defined('DB_PORT') ? DB_PORT : '3306';
$defaultDb   = defined('DB_NAME') ? DB_NAME : 'bfms_lublub';
$defaultUser = defined('DB_USER') ? DB_USER : 'root';
$defaultPass = defined('DB_PASS') ? DB_PASS : '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $dbHost = clean($_POST['db_host'] ?? $defaultHost);
    $dbPort = clean($_POST['db_port'] ?? $defaultPort);
    $dbName = clean($_POST['db_name'] ?? $defaultDb);
    $dbUser = clean($_POST['db_user'] ?? $defaultUser);
    $dbPass = $_POST['db_pass'] ?? $defaultPass;

    try {
        $pdo = null;

        // 1. First attempt: Direct connection to target database (Standard on Hostinger where DB is created in hPanel)
        try {
            $dsn = "mysql:host={$dbHost};port={$dbPort};dbname={$dbName};charset=utf8mb4";
            $pdo = new PDO($dsn, $dbUser, $dbPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            ]);
        } catch (PDOException $ex) {
            // 2. Fallback for Localhost: connect to server and create database if missing
            $serverDsn = "mysql:host={$dbHost};port={$dbPort};charset=utf8mb4";
            $serverPdo = new PDO($serverDsn, $dbUser, $dbPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION
            ]);
            $serverPdo->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            
            $pdo = new PDO("mysql:host={$dbHost};port={$dbPort};dbname={$dbName};charset=utf8mb4", $dbUser, $dbPass, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION
            ]);
        }

        // 3. Read and execute database/schema.sql
        $schemaFile = __DIR__ . '/database/schema.sql';
        if (!file_exists($schemaFile)) {
            throw new Exception("schema.sql file not found in database/ directory.");
        }

        $sql = file_get_contents($schemaFile);

        // Remove CREATE DATABASE / USE statements from SQL dump if connecting to a pre-created Hostinger database
        $cleanSql = preg_replace('/CREATE\s+DATABASE[^\;]+;/i', '', $sql);
        $cleanSql = preg_replace('/USE\s+[`a-zA-Z0-9_\-]+;/i', '', $cleanSql);

        $pdo->exec($cleanSql);

        // 4. Save credentials to config/db_config.php for permanent persistence on Hostinger & Localhost
        $configContent = "<?php\n// Auto-generated by BFMS Setup Wizard\nreturn [\n"
            . "    'host'     => " . var_export($dbHost, true) . ",\n"
            . "    'port'     => " . var_export($dbPort, true) . ",\n"
            . "    'database' => " . var_export($dbName, true) . ",\n"
            . "    'username' => " . var_export($dbUser, true) . ",\n"
            . "    'password' => " . var_export($dbPass, true) . ",\n"
            . "];\n";

        @file_put_contents(__DIR__ . '/config/db_config.php', $configContent);

        $message = "Database `{$dbName}` and initial seed data have been successfully configured and imported!";
        $connected = true;

        log_activity('Database Setup', "Database {$dbName} configured via setup wizard");
    } catch (Exception $e) {
        $error = "Setup Error: " . $e->getMessage();
    }
}
